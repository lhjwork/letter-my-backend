function randomNickname(): string {
  const adj = ADJECTIVES[Math.floor(Math.random() * ADJECTIVES.length)];
  const animal = ANIMALS[Math.floor(Math.random() * ANIMALS.length)];
  const num = Math.floor(Math.random() * 90) + 10; // 10~99
  return `${adj}${animal}${num}`;
}

/**
 * 중복되지 않는 익명 닉네임 생성 (예: 귀여운곰42)
 */
export async function generateUniqueNickname(): Promise<string> {
  for (let i = 0; i < 10; i++) {
    const nickname = randomNickname();
    const exists = await User.exists({ name: nickname });
    if (!exists) return nickname;
  }
  // ponytail: 10회 충돌 시 4자리 숫자로 확장 — 사실상 도달 불가
  const adj = ADJECTIVES[Math.floor(Math.random() * ADJECTIVES.length)];
  const animal = ANIMALS[Math.floor(Math.random() * ANIMALS.length)];
  return `${adj}${animal}${Math.floor(Math.random() * 9000) + 1000}`;
}
